const {chromium}=require('playwright-core');
const ok=(c,m)=>{console.log((c?'ok: ':'FAIL: ')+m); if(!c) process.exitCode=1;};
const num=s=>parseFloat(s.replace(/[^\d.]/g,'').replace(/^\./,''));
(async()=>{const b=await chromium.launch({executablePath:'/opt/pw-browsers/chromium',ignoreDefaultArgs:['--headless=old'],args:['--no-sandbox','--headless=new']});
const pg=await (await b.newContext({viewport:{width:390,height:844}})).newPage(); const errs=[]; pg.on('pageerror',e=>errs.push(e.message));
await pg.goto((process.env.BASE||'http://localhost:8768/')); await pg.waitForTimeout(500);
await pg.fill('#searchInput','60240'); await pg.waitForTimeout(250); await pg.click('.result-row[data-codigo="60240"]');
await pg.click('#cartTab'); await pg.waitForTimeout(200);
const t=async id=>num(await pg.textContent('#'+id));
ok(!(await pg.isVisible('#segRowVisitas')),'sin visitas no aparece la fila');
const totalCon=await t('totalCon'), cir0=await t('segPacienteCirujano');
await pg.fill('#visitasN','2'); await pg.waitForTimeout(150);
const cir=await t('segPacienteCirujano'), ay=await t('segPacienteAyudante'), an=await t('segPacienteAnest'), vis=await t('segPacienteVisitas'), tot=await t('segTotalPaciente');
ok(vis===7000,'privado: 2 × 3,500 = 7,000');
ok(Math.abs((cir+ay+an)-(totalCon-7000))<=15,'privado: honorarios suman total − visitas ('+(cir+ay+an)+' vs '+(totalCon-7000)+')');
ok(Math.abs(ay/cir-0.33)<0.002 && Math.abs(an/cir-0.33)<0.002,'privado: misma proporción 33 % entre participantes');
ok(tot===cir+ay+an+vis && cir<cir0,'privado: total = honorarios recalculados + visitas');
await pg.fill('#visitasValor','4000'); await pg.waitForTimeout(150);
ok(await t('segPacienteVisitas')===8000,'valor de la visita editable (2 × 4,000)');
await pg.check('#seguroToggle'); await pg.waitForTimeout(150);
const sc=await t('segPacienteCirujano'), sa=await t('segPacienteAyudante'), sn=await t('segPacienteAnest');
ok(Math.abs(await t('segTotalPaciente')-(sc+sa+sn+8000))<0.01 && (await pg.textContent('#segVisitasLabel')).includes('aparte'),'seguro: visitas aparte, sumadas al copago');
await pg.evaluate(()=>{ navigator.share=undefined; navigator.clipboard.writeText=async t=>{window.__t=t}; });
await pg.click('#btnSharePatient'); await pg.waitForTimeout(200);
ok((await pg.evaluate(()=>window.__t)).includes('Visitas médicas (2)'),'presupuesto incluye las visitas');
await pg.click('#btnClearCart'); await pg.click('#btnClearCart'); await pg.waitForTimeout(200);
ok(await pg.inputValue('#visitasN')==='0' && await pg.inputValue('#visitasValor')==='3500','vaciar: 0 visitas, L 3,500');
console.log('errors',errs); await b.close();})();
